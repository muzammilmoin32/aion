const ROOT_ATTR = /^((?:\[(?:dir|lang|data-lens|data-behind|data-theme)(?:[~|^$*]?=[^\]]*)?\])+)/;
function scopeSel(sel) {
  let s = sel.trim();
  s = s.replace(/:has\(body\.night\)/g, '');
  // the night skin is always on inside the section
  s = s.replace(/^\[data-skin="night"\]\s*/, '').replace(/^(:root|html)\[data-skin="night"\]/, '$1');
  if (/^#th-stream\b/.test(s)) return s;                       // the stream canvas lives outside the section
  if (/^(#th-|html\.th-boot|\.th-boot)/.test(s)) return null;  // loader, grain, cursor ring: not used here
  let rootCond = ''; let rest = s;
  const m = s.match(/^(:root|html)((?:\[[^\]]*\]|:not\([^)]*\)|\.[\w-]+)*)/);
  if (m) { rootCond = m[2]; rest = s.slice(m[0].length).trim(); } else {
    const a = s.match(ROOT_ATTR);
    if (a) { rootCond = a[1]; rest = s.slice(a[0].length).trim(); }
  }
  rest = rest.replace(/^body(?:\.night)?(?=[\s.:[>+~]|$)/, SCOPE).replace(/^\.night(?=[\s.:[>+~]|$)/, SCOPE);
  const inner = !rest ? SCOPE : rest.startsWith(SCOPE) ? rest : `${SCOPE} ${rest}`;
  return rootCond ? `:root${rootCond} ${inner}` : inner;
}
function scopeCss(css, file) {
  const tree = postcss.parse(css, { from: file });
  const frames = new Set();
  tree.walkAtRules(/keyframes$/, (r) => { frames.add(r.params.trim()); });
  tree.walkAtRules(/keyframes$/, (r) => { r.params = `g-${r.params.trim()}`; });
  tree.walkDecls(/^(animation|animation-name)$/, (d) => {
    d.value = d.value.replace(/[\w-]+/g, (w) => (frames.has(w) ? `g-${w}` : w));
  });
  tree.walkRules((r) => {
    if (r.parent && r.parent.type === 'atrule' && /keyframes$/.test(r.parent.name)) return;
    const out = r.selectors.map(scopeSel).filter(Boolean);
    if (!out.length) r.remove(); else r.selectors = [...new Set(out)];
  });
  return tree.toString();
}
