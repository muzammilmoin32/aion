let problems = 0;
const must = (src, find, repl, label) => {
  if (!src.includes(find)) { console.log('NOT FOUND:', label); problems += 1; return src; }
  return src.replace(find, () => repl);
};
const cut = (src, startMark, endMark, label) => {
  const a = src.indexOf(startMark); const b = a < 0 ? -1 : src.indexOf(endMark, a);
  if (a < 0 || b < 0) { console.log('NOT FOUND:', label); problems += 1; return null; }
  return { a, b: b + endMark.length, text: src.slice(a, b + endMark.length) };
};

