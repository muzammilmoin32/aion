const PANEL = /\.(tilt|tilt-grid|runline|foot-note|stage|g3d|gback|gpanel|g-top|gchips?|gctl|switch|gpause|gbody|gphone|gphone-wrap|gscreen|gs-[a-z]+|gfloat|gf-step|gf-time|gsteps)(?![\w-])/;
function dropPanelCss(html) {
  const st = cut(html, '<style>', '</style>', 'theme style block');
  if (!st) return html;
  const tree = postcss.parse(st.text.slice('<style>'.length, -'</style>'.length));
  let dropped = 0;
  tree.walkRules((r) => {
    if (r.parent && r.parent.type === 'atrule' && /keyframes$/.test(r.parent.name)) return;
    const keep = r.selectors.filter((s) => !PANEL.test(s));
    dropped += r.selectors.length - keep.length;
    if (!keep.length) { r.remove(); return; }
    // fence every theme rule out of the glass section (it shares class names like .hero, .toast, .chip, .btn);
    // :where() keeps each rule's specificity exactly as it was everywhere else
    r.selectors = keep.map((s) => {
      const pe = s.match(/(::[\w-]+(?:\([^)]*\))?)$/);
      const head = pe ? s.slice(0, -pe[1].length) : s;
      return `${head}:not(:where(${SCOPE} *))${pe ? pe[1] : ''}`;
    });
  });
  if (!dropped) { console.log('NOT FOUND: theme panel rules'); problems += 1; }
  return html.slice(0, st.a) + `<style>${tree.toString()}</style>` + html.slice(st.b);
}
